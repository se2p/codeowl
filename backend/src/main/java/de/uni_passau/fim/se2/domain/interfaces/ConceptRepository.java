package de.uni_passau.fim.se2.domain.interfaces;

import de.uni_passau.fim.se2.domain.entities.*;
import de.uni_passau.fim.se2.domain.entities.ConceptDTO;

import java.util.*;

/**
 * Repository interface for managing programming concepts.
 * Provides methods for loading, saving, and deleting instances
 * of programming concepts encapsulated as ConceptDTO objects.
 */
public interface ConceptRepository {
    /**
     * Loads the details of a programming concept into the specified ConceptDTO instance.
     * This method typically retrieves concept information from the repository and populates
     * the target ConceptDTO object.
     *
     * @param target the ConceptDTO instance to be populated with the details
     *               of the programming concept
     */
    void loadById(ConceptDTO target);
    /**
     * Loads the details of a programming concept into the specified ConceptDTO instance.
     * The method retrieves the concept information from the repository using its name
     * and populates the target ConceptDTO object.
     *
     * @param target the ConceptDTO instance to be populated with the details
     *               of the programming concept identified by its name
     */
    void loadByName(ConceptDTO target);
    /**
     * Loads all programming concepts not generated by users stored in the repository.
     *
     * @return a list of ConceptDTO objects representing all the programming concepts
     *         available, or an empty list if no concepts are found
     */
    List<ConceptDTO> loadAllOriginal();
    /**
     * Saves the specified programming concept to the repository.
     * This method persists the provided ConceptDTO object, allowing
     * it to be retrieved or modified at a later time.
     *
     * @param concept the ConceptDTO object representing the programming concept
     *                to be saved into the repository
     */
    UUID save(ConceptDTO concept);

    /**
     * Batch variant of {@link #save(ConceptDTO)} (OPT-6). Inserts all provided concepts in a single
     * round-trip (ON CONFLICT DO NOTHING) and returns the resolved IDs for each name in input order.
     *
     * @param concepts the concept DTOs to persist (name must be set; description optional)
     * @return list of UUIDs matching the input names in the same order; never null
     */
    List<UUID> saveAll(List<ConceptDTO> concepts);

    /**
     * Deletes the specified programming concept from the repository.
     * This method removes the provided ConceptDTO instance and its associated data.
     *
     * @param concept the ConceptDTO object representing the programming concept to be deleted
     */
    void delete(ConceptDTO concept);
}